#!/bin/bash
# 批量运行所有中文名.py分析脚本，分析多只个股
# 结果自动保存到 results/{脚本名}/{yyyymmdd}/ 目录
# 用法: bash run_all_analysis.sh

set -e

SCRIPT_DIR="$(cd "$(dirname "$0")" && pwd)"
cd "$SCRIPT_DIR"

export MPLBACKEND=Agg
export PYTHONIOENCODING=utf-8

TODAY=$(date +%Y-%m-%d)
START_DATE="2008-01-01"
START_DATE_SHORT="2024-01-01"  # 模拟持仓使用较短的日期范围

# 股票列表 (按指定顺序)
CODES=("601857" "600941" "000001" "600519" "688256" "688981")
NAMES=("中国石油" "中国移动" "上证指数" "贵州茅台" "寒武纪" "中芯国际")
N=${#CODES[@]}

echo "=========================================="
echo "批量股票分析 - 开始执行"
echo "日期: $TODAY"
echo "股票数量: $N"
echo "=========================================="
echo ""

# ============================================================
# 通过管道输入运行交互式脚本
# 参数: $1=脚本路径, $2=股票代码, $3=股票名称, $4=起始日期, $5=结束日期, $6=额外输入(如周期选择)
# ============================================================
run_with_input() {
    local script="$1"
    local code="$2"
    local name="$3"
    local start="$4"
    local end="$5"
    local extra="${6:-}"

    echo "  >> $script - $code $name"

    if [ -n "$extra" ]; then
        # 有额外输入(如周期选择)
        printf '%s\n' "$code" "$name" "$start" "$end" "$extra" | python3 "$script"
    else
        # 4行输入
        printf '%s\n' "$code" "$name" "$start" "$end" | python3 "$script"
    fi

    local rc=$?
    if [ $rc -eq 0 ]; then
        echo "  ✓ $code $name 完成"
    else
        echo "  ✗ $code $name 失败 (exit code: $rc)"
    fi
    echo ""
}

# ============================================================
# 通过命令行参数运行模拟持仓
# ============================================================
run_mock() {
    local code="$1"
    local start="$2"
    local end="$3"

    echo "  >> 模拟持仓.py - $code"
    python3 模拟持仓.py --code "$code" --start "$start" --end "$end" --no-chart
    local rc=$?
    if [ $rc -eq 0 ]; then
        echo "  ✓ $code 完成"
    else
        echo "  ✗ $code 失败 (exit code: $rc)"
    fi
    echo ""
}

# ============================================================
# 1. 节日涨跌分析 (输入: code, name, start, end)
# ============================================================
echo "=========================================="
echo "1/7 节日涨跌分析 (${N}只)"
echo "=========================================="
for ((i=0; i<N; i++)); do
    run_with_input "节日涨跌分析.py" "${CODES[$i]}" "${NAMES[$i]}" "$START_DATE" "$TODAY"
done

# ============================================================
# 2. 星期涨跌分析 (输入: code, name, start, end)
# ============================================================
echo "=========================================="
echo "2/7 星期涨跌分析 (${N}只)"
echo "=========================================="
for ((i=0; i<N; i++)); do
    run_with_input "星期涨跌分析.py" "${CODES[$i]}" "${NAMES[$i]}" "$START_DATE" "$TODAY"
done

# ============================================================
# 3. 模拟持仓 (命令行: --code, --start, --end, --no-chart)
# ============================================================
echo "=========================================="
echo "3/7 模拟持仓 (${N}只)"
echo "=========================================="
for ((i=0; i<N; i++)); do
    run_mock "${CODES[$i]}" "$START_DATE_SHORT" "$TODAY"
done

# ============================================================
# 4. 线性回归 (输入: code, name, start, end, period=1)
# ============================================================
echo "=========================================="
echo "4/7 线性回归 (${N}只)"
echo "=========================================="
for ((i=0; i<N; i++)); do
    run_with_input "线性回归.py" "${CODES[$i]}" "${NAMES[$i]}" "$START_DATE" "$TODAY" "1"
done

# ============================================================
# 5. 波动分析 (输入: code, name, start, end, period=1)
# ============================================================
echo "=========================================="
echo "5/7 波动分析 (${N}只)"
echo "=========================================="
for ((i=0; i<N; i++)); do
    run_with_input "波动分析.py" "${CODES[$i]}" "${NAMES[$i]}" "$START_DATE" "$TODAY" "1"
done

# ============================================================
# 6. 股票模拟 (无输入，纯随机模拟)
# ============================================================
echo "=========================================="
echo "6/7 股票模拟 (纯随机模拟)"
echo "=========================================="
echo "  >> 股票模拟.py"
python3 股票模拟.py && echo "  ✓ 完成" || echo "  ✗ 失败"
echo ""

# ============================================================
# 7. 随机漫步 (无输入，纯随机模拟)
# ============================================================
echo "=========================================="
echo "7/7 随机漫步 (纯随机模拟)"
echo "=========================================="
echo "  >> 随机漫步.py"
python3 随机漫步.py && echo "  ✓ 完成" || echo "  ✗ 失败"
echo ""

# ============================================================
# 完成
# ============================================================
echo "=========================================="
echo "全部分析完成!"
echo "结果目录:"
echo "=========================================="
find results -type f -name "*.jpg" -o -name "*.txt" 2>/dev/null | sort
