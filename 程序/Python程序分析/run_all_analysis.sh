#!/bin/bash
# 批量运行股票分析统一入口(股票分析.py)的各个功能，分析多只个股
# 结果自动保存到 results/{功能名}/{yyyymmdd}/ 目录
# 用法: bash run_all_analysis.sh

set -e

SCRIPT_DIR="$(cd "$(dirname "$0")" && pwd)"
cd "$SCRIPT_DIR"

export MPLBACKEND=Agg
export PYTHONIOENCODING=utf-8

TODAY=$(date +%Y-%m-%d)
START_DATE="2008-01-01"
START_DATE_SHORT="2024-01-01"  # 模拟持仓使用较短的日期范围

# 股票列表 (按指定顺序)
CODES=("601857" "600941" "000001" "600519" "688256" "688981")
NAMES=("中国石油" "中国移动" "上证指数" "贵州茅台" "寒武纪" "中芯国际")
N=${#CODES[@]}

echo "=========================================="
echo "批量股票分析 - 开始执行"
echo "日期: $TODAY"
echo "股票数量: $N"
echo "=========================================="
echo ""

# ============================================================
# 通过统一入口子命令运行（行情类功能：code/name/start/end/no-chart）
# 参数: $1=功能名, $2=股票代码, $3=股票名称, $4=起始日期, $5=结束日期, $6=额外参数(如 --period daily)
# ============================================================
run_entry() {
    local tool="$1"
    local code="$2"
    local name="$3"
    local start="$4"
    local end="$5"
    local extra="${6:-}"

    echo "  >> 股票分析.py $tool - $code $name"

    # shellcheck disable=SC2086
    python 股票分析.py "$tool" --code "$code" --name "$name" \
        --start "$start" --end "$end" --no-chart $extra

    local rc=$?
    if [ $rc -eq 0 ]; then
        echo "  ✓ $code $name 完成"
    else
        echo "  ✗ $code $name 失败 (exit code: $rc)"
    fi
    echo ""
}

# ============================================================
# 通过命令行参数运行模拟持仓（无 --name 参数）
# ============================================================
run_mock() {
    local code="$1"
    local start="$2"
    local end="$3"

    echo "  >> 股票分析.py 模拟持仓 - $code"
    python 股票分析.py 模拟持仓 --code "$code" --start "$start" --end "$end" --no-chart
    local rc=$?
    if [ $rc -eq 0 ]; then
        echo "  ✓ $code 完成"
    else
        echo "  ✗ $code 失败 (exit code: $rc)"
    fi
    echo ""
}

# ============================================================
# 1. 节日涨跌分析 (--code/--name/--start/--end)
# ============================================================
echo "=========================================="
echo "1/7 节日涨跌分析 (${N}只)"
echo "=========================================="
for ((i=0; i<N; i++)); do
    run_entry "节日涨跌分析" "${CODES[$i]}" "${NAMES[$i]}" "$START_DATE" "$TODAY"
done

# ============================================================
# 2. 星期涨跌分析 (--code/--name/--start/--end)
# ============================================================
echo "=========================================="
echo "2/7 星期涨跌分析 (${N}只)"
echo "=========================================="
for ((i=0; i<N; i++)); do
    run_entry "星期涨跌分析" "${CODES[$i]}" "${NAMES[$i]}" "$START_DATE" "$TODAY"
done

# ============================================================
# 3. 模拟持仓 (命令行: --code, --start, --end, --no-chart)
# ============================================================
echo "=========================================="
echo "3/7 模拟持仓 (${N}只)"
echo "=========================================="
for ((i=0; i<N; i++)); do
    run_mock "${CODES[$i]}" "$START_DATE_SHORT" "$TODAY"
done

# ============================================================
# 4. 线性回归 (--period daily)
# ============================================================
echo "=========================================="
echo "4/7 线性回归 (${N}只)"
echo "=========================================="
for ((i=0; i<N; i++)); do
    run_entry "线性回归" "${CODES[$i]}" "${NAMES[$i]}" "$START_DATE" "$TODAY" "--period daily"
done

# ============================================================
# 5. 波动分析 (--period daily)
# ============================================================
echo "=========================================="
echo "5/7 波动分析 (${N}只)"
echo "=========================================="
for ((i=0; i<N; i++)); do
    run_entry "波动分析" "${CODES[$i]}" "${NAMES[$i]}" "$START_DATE" "$TODAY" "--period daily"
done

# ============================================================
# 6. 股票模拟 (无输入，纯随机模拟)
# ============================================================
echo "=========================================="
echo "6/7 股票模拟 (纯随机模拟)"
echo "=========================================="
echo "  >> 股票模拟.py"
python 股票模拟.py && echo "  ✓ 完成" || echo "  ✗ 失败"
echo ""

# ============================================================
# 7. 随机漫步 (无输入，纯随机模拟)
# ============================================================
echo "=========================================="
echo "7/7 随机漫步 (纯随机模拟)"
echo "=========================================="
echo "  >> 随机漫步.py"
python 随机漫步.py && echo "  ✓ 完成" || echo "  ✗ 失败"
echo ""

# ============================================================
# 完成
# ============================================================
echo "=========================================="
echo "全部分析完成!"
echo "结果目录:"
echo "=========================================="
find results -type f -name "*.jpg" -o -name "*.txt" 2>/dev/null | sort
